// Command geninstall writes the installers of the two applications,
// install-system.sh and install-dev.sh, from the template
// scripts/install.sh.in, replacing its @NAME@ placeholders with each
// application's values.
//
//	go run ./tools/geninstall          write the installers
//	go run ./tools/geninstall -check   write nothing; fail when one differs
//
// It runs from the repository root.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// templatePath is the installer template, relative to the repository root.
const templatePath = "scripts/install.sh.in"

// generatedNotice replaces @GENERATED_NOTICE@: the marker of a generated
// file.
const generatedNotice = "# Code generated by geninstall. DO NOT EDIT."

// app holds the values one installer is generated with.
type app struct {
	// Out is the installer's path, relative to the repository root.
	Out string
	// Values maps each placeholder name to its value.
	Values map[string]string
}

// apps lists the generated installers.
var apps = []app{
	{Out: "install-system.sh", Values: map[string]string{
		"APP": "system", "BINARY": "perci82-system", "TITLE": "Perci82 System",
	}},
	{Out: "install-dev.sh", Values: map[string]string{
		"APP": "dev", "BINARY": "perci82-dev", "TITLE": "Perci82 Dev",
	}},
}

// placeholder matches an @NAME@ placeholder of the template.
var placeholder = regexp.MustCompile(`@([A-Z_]+)@`)

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

// run parses args, then writes or checks the installers, returning the
// exit code.
func run(args []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("geninstall", flag.ContinueOnError)
	flags.SetOutput(stderr)
	check := flags.Bool("check", false, "fail when an installer differs from the generated one")
	dir := flags.String("dir", ".", "repository root")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	tpl, err := os.ReadFile(filepath.Join(*dir, templatePath))
	if err != nil {
		fmt.Fprintln(stderr, "Error:", err)
		return 1
	}
	stale := false
	for _, a := range apps {
		out, err := render(string(tpl), a.Values)
		if err != nil {
			fmt.Fprintf(stderr, "Error: %s: %v\n", a.Out, err)
			return 1
		}
		path := filepath.Join(*dir, a.Out)
		if *check {
			current, err := os.ReadFile(path)
			if err != nil && !errors.Is(err, os.ErrNotExist) {
				fmt.Fprintln(stderr, "Error:", err)
				return 1
			}
			if !bytes.Equal(current, []byte(out)) {
				fmt.Fprintf(stderr, "%s is out of date: run `make generate`\n", a.Out)
				stale = true
			}
			continue
		}
		if err := os.WriteFile(path, []byte(out), 0o755); err != nil { //nolint:gosec // an installer script is executable
			fmt.Fprintln(stderr, "Error:", err)
			return 1
		}
		if err := os.Chmod(path, 0o755); err != nil { //nolint:gosec // an installer script is executable
			fmt.Fprintln(stderr, "Error:", err)
			return 1
		}
	}
	if stale {
		return 1
	}
	return 0
}

// render replaces every placeholder of tpl: @GENERATED_NOTICE@ with
// generatedNotice and the others with values. A placeholder without a
// value is an error.
func render(tpl string, values map[string]string) (string, error) {
	var missing []string
	out := placeholder.ReplaceAllStringFunc(tpl, func(m string) string {
		name := m[1 : len(m)-1]
		if name == "GENERATED_NOTICE" {
			return generatedNotice
		}
		v, ok := values[name]
		if !ok {
			missing = append(missing, name)
			return m
		}
		return v
	})
	if len(missing) > 0 {
		return "", fmt.Errorf("no value for %s", strings.Join(missing, ", "))
	}
	return out, nil
}
