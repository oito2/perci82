// The "PHP Perci82" standard: PHP-PERCI82.md is written from the settings
// of the Docker app whose project root (or a development folder mounted
// into it) holds the project — its command and tools, versions, URL,
// folders, database and mounts. Its first line carries the SHA-256 of the
// rest, so a copy written for earlier app settings is outdated rather
// than edited.

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/oito2/perci82/internal/appstack"
	"github.com/oito2/perci82/internal/config"
)

// phpPerciName is the standard's name (its ID in config and export files).
const phpPerciName = "PHP Perci82"

// phpGuideMarker starts the first line of PHP-PERCI82.md, followed by the
// SHA-256 of the rest of the file and " -->".
const phpGuideMarker = "<!-- Generated by Perci82 Dev from the Docker app's settings. sha256="

// signGuide returns body with its signed first line.
func signGuide(body string) string {
	sum := sha256.Sum256([]byte(body))
	return phpGuideMarker + hex.EncodeToString(sum[:]) + " -->\n" + body
}

// signedUnedited reports whether data is a PHP-PERCI82.md whose content
// still matches its signature: written by Perci, for any app settings.
func signedUnedited(data string) bool {
	first, body, ok := strings.Cut(data, "\n")
	if !ok || !strings.HasPrefix(first, phpGuideMarker) || !strings.HasSuffix(first, " -->") {
		return false
	}
	want := strings.TrimSuffix(strings.TrimPrefix(first, phpGuideMarker), " -->")
	sum := sha256.Sum256([]byte(body))
	return want == hex.EncodeToString(sum[:])
}

// phpApp is the Docker app a project runs in: the app, and the
// development folder mount that holds the project ("" when the project is
// the app's own project root).
type phpApp struct {
	app       config.AppContainer
	workspace string
	mount     *config.MoodlePluginMount
	mounts    []config.MoodlePluginMount
	mariadb   config.MariaDBConfig
}

// within reports whether path is root or inside it, links resolved.
func pathWithin(root, path string) bool {
	if r, err := filepath.EvalSymlinks(root); err == nil {
		root = r
	}
	if p, err := filepath.EvalSymlinks(path); err == nil {
		path = p
	}
	rel, err := filepath.Rel(root, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, "../")
}

// phpAppFor finds the Docker app with PHP whose project root, or one of
// whose mounted development folders, holds dir; ok is false when none
// does or the config can't be read.
func phpAppFor(dir string) (phpApp, bool) {
	cfg, err := config.Load()
	if err != nil || dir == "" {
		return phpApp{}, false
	}
	workspace, err := cfg.Workspace()
	if err != nil {
		return phpApp{}, false
	}
	for _, a := range cfg.Docker.Apps {
		if a.Type == config.AppTypeNode {
			continue
		}
		found := phpApp{app: a, workspace: workspace, mariadb: cfg.Docker.MariaDB}
		for _, m := range cfg.MoodlePlugins {
			if m.App == a.Folder {
				found.mounts = append(found.mounts, m)
			}
		}
		if pathWithin(appstack.AppHTMLDir(workspace, a.Folder), dir) {
			return found, true
		}
		for i, m := range found.mounts {
			if pathWithin(m.DevPath, dir) {
				found.mount = &found.mounts[i]
				return found, true
			}
		}
	}
	return phpApp{}, false
}

// appTypeLabels names the app types with PHP, in English.
var appTypeLabels = map[string]string{
	config.AppTypeMoodle:  "Moodle",
	config.AppTypePHP:     "PHP",
	config.AppTypeGeneric: "Generic",
	config.AppTypePHPNode: "PHP + Node",
}

// moodle51 reports whether a Moodle app's version uses the public/ layout.
func moodle51(a config.AppContainer) bool {
	return a.MoodleVersion == "" || a.MoodleVersion == "5.1+"
}

// vars fills the placeholders of PHP-PERCI82.md.
func (p phpApp) vars() map[string]string {
	a := p.app
	cmd := "`" + a.Folder
	root := appstack.AppHTMLDir(p.workspace, a.Folder)
	moodle := a.Type == config.AppTypeMoodle

	moodleRows := ""
	if moodle {
		v := a.MoodleVersion
		if v == "" {
			v = "5.1+"
		}
		moodleRows = "| Moodle | " + v + " |\n"
	}

	roots := "`" + root + "` on the host = `/var/www/html` in the container"
	if a.Type == config.AppTypePHPNode {
		roots = "`" + appstack.AppComboAPIDir(p.workspace, a.Folder) + "` = `/var/www/html` (PHP) and `" +
			appstack.AppComboAppDir(p.workspace, a.Folder) + "` = `/app` (Node) in the container"
	}
	if p.mount != nil {
		if cp, ok := appstack.ContainerPath(a.Type, p.mount.RelPath); ok {
			roots += "; this project is the development folder `" + p.mount.DevPath + "`, mounted at `" + cp + "`"
		}
	}

	var rows []string
	rows = append(rows, "| "+cmd+" <file or php options>` | PHP |")
	var off []string
	if appstack.ToolEnabled(a, appstack.ToolComposer) {
		rows = append(rows, "| "+cmd+" composer …` | Composer |")
	} else {
		off = append(off, "composer")
	}
	if appstack.ToolEnabled(a, appstack.ToolPHPUnit) {
		what := "The container's global PHPUnit; the project's own (from `composer.lock`) runs with " + cmd + " vendor/bin/phpunit`"
		if moodle {
			what = "The container's global PHPUnit, **not** Moodle's: run Moodle's tests with " + cmd + " vendor/bin/phpunit`"
		}
		rows = append(rows, "| "+cmd+" phpunit …` | "+what+" |")
	} else {
		off = append(off, "phpunit")
	}
	if appstack.ToolEnabled(a, appstack.ToolPHPCS) {
		what := "The container's global PHP_CodeSniffer"
		switch {
		case moodle && appstack.ToolEnabled(a, appstack.ToolMoodleCS):
			what = "PHP_CodeSniffer with the `moodle` standard: " + cmd + " phpcs --standard=moodle <path>`"
		case moodle:
			what = "The container's global PHP_CodeSniffer, **without** the `moodle` standard (moodle-cs is off for this app)"
		}
		rows = append(rows, "| "+cmd+" phpcs …` / "+cmd+" phpcbf …` | "+what+" |")
	} else {
		off = append(off, "phpcs, phpcbf")
	}
	if a.Type == config.AppTypePHPNode {
		rows = append(rows, "| "+cmd+" npm …` | npm (run it from `app/` to work in `/app`) |")
	}

	var notes []string
	if len(off) > 0 {
		notes = append(notes, "- Turned off in this app: "+strings.Join(off, ", ")+".")
	}
	if moodle {
		cli := "admin/cli"
		if moodle51(a) {
			cli = "public/admin/cli"
			notes = append(notes, "- The web server already serves `public/`: `$CFG->wwwroot` is the app URL, without `/public`.")
		}
		notes = append(notes, "- Moodle CLI scripts: "+cmd+" "+cli+"/upgrade.php --non-interactive`, "+cmd+" "+cli+"/purge_caches.php`.")
	}
	toolNotes := ""
	if len(notes) > 0 {
		toolNotes = strings.Join(notes, "\n") + "\n"
	}

	database := "This app has no database access; it is turned on in Perci82 Dev (Docker → Manage Containers → Edit)."
	if a.DBAccess {
		user := p.mariadb.DBUser
		database = fmt.Sprintf("- MariaDB: host `%s`, port 3306, database `dev_db`, user `%s`. The app gets them as `DB_HOST`, `DB_PORT`, `DB_NAME`, `DB_USER` and `DB_PASS`.\n"+
			"- The password is only in the app's environment (`DB_PASS`): never write it into files.\n"+
			"- Open a client: `docker exec -it %s mariadb -u %s -p dev_db` (it asks for the password).",
			appstack.MariaDBContainerName, user, appstack.MariaDBContainerName, user)
	}

	mounts := "None."
	if len(p.mounts) > 0 {
		var lines []string
		for _, m := range p.mounts {
			cp, ok := appstack.ContainerPath(a.Type, m.RelPath)
			if !ok {
				continue
			}
			line := "- `" + m.DevPath + "` → `" + cp + "`"
			if m.Component != "" {
				line += " (" + m.Component + ")"
			}
			lines = append(lines, line)
		}
		mounts = strings.Join(lines, "\n") + "\n\nEdits in a development folder show in the app at once; a new mount needs the app restarted in Perci82 Dev."
	}

	return map[string]string{
		"APP":         a.Folder,
		"APP_TYPE":    appTypeLabels[a.Type],
		"APP_URL":     "https://" + a.URL,
		"PHP_VERSION": a.PHPVersion,
		"MOODLE_ROWS": moodleRows,
		"ROOTS":       roots,
		"TOOL_ROWS":   strings.Join(rows, "\n"),
		"FALLBACK":    "php",
		"TOOL_NOTES":  toolNotes,
		"DATABASE":    database,
		"MOUNTS":      mounts,
		"LOGS":        "- PHP and web server logs: `" + appstack.AppLogDir(p.workspace, a.Folder) + "` on the host.",
	}
}

// phpGuideFor returns PHP-PERCI82.md as Perci writes it for the project in
// dir, and the app's command; ok is false when no Docker app holds dir.
func phpGuideFor(dir string) (content, command string, ok bool, err error) {
	p, found := phpAppFor(dir)
	if !found {
		return "", "", false, nil
	}
	tpl, err := readTpl("templates/instructions/PHP-PERCI82.md")
	if err != nil {
		return "", "", false, err
	}
	return signGuide(substitute(tpl, p.vars())), p.app.Folder, true, nil
}

// applicable returns active without the standards that can't be written
// for the project in dir (PHP Perci82 when no Docker app holds it), and
// whether one was dropped.
func applicable(dir string, active []Model) ([]Model, bool) {
	if _, _, ok, err := phpGuideFor(dir); ok || err != nil {
		return active, false
	}
	out := make([]Model, 0, len(active))
	dropped := false
	for _, m := range active {
		if m.Name == phpPerciName {
			dropped = true
			continue
		}
		out = append(out, m)
	}
	return out, dropped
}
