// writeTokens writes the :root rule with the design tokens.
func writeTokens(b *strings.Builder, t Tokens) {
	b.WriteString(":root {\n")
	for _, k := range slices.Sorted(maps.Keys(t.Radius)) {
		fmt.Fprintf(b, "\t--oito2-radius-%s: %spx;\n", kebab(k), number(t.Radius[k]))
	}
	for _, k := range slices.Sorted(maps.Keys(t.Spacing)) {
		fmt.Fprintf(b, "\t--oito2-space-%s: %spx;\n", kebab(k), number(t.Spacing[k]))
	}
	// The group already says "size": iconSize becomes --oito2-size-icon.
	for _, k := range slices.Sorted(maps.Keys(t.Sizes)) {
		fmt.Fprintf(b, "\t--oito2-size-%s: %spx;\n", kebab(strings.TrimSuffix(k, "Size")), number(t.Sizes[k]))
	}
	for _, k := range slices.Sorted(maps.Keys(t.Accents)) {
		fmt.Fprintf(b, "\t--oito2-accent-%s: %s;\n", kebab(k), strings.ToLower(t.Accents[k]))
	}
	families := make([]string, 0, len(t.Typography.FontFamilyFallback)+1)
	for _, f := range t.Typography.FontFamilyFallback {
		if strings.Contains(f, " ") {
			f = "'" + f + "'"
		}
		families = append(families, f)
	}
	families = append(families, "sans-serif")
	fmt.Fprintf(b, "\t--oito2-font-family: %s;\n", strings.Join(families, ", "))
	fmt.Fprintf(b, "\t--oito2-font-weight-emphasis: %d;\n", t.Typography.EmphasisWeight)
	for _, k := range slices.Sorted(maps.Keys(t.Typography.Scale)) {
		s := t.Typography.Scale[k]
		p := "--oito2-type-" + kebab(k)
		fmt.Fprintf(b, "\t%s-size: %spx;\n", p, number(s.FontSize))
		fmt.Fprintf(b, "\t%s-line-height: %spx;\n", p, number(s.LineHeight))
		fmt.Fprintf(b, "\t%s-weight: %d;\n", p, s.FontWeight)
		fmt.Fprintf(b, "\t%s-tracking: %spx;\n", p, number(s.LetterSpacing))
	}
	b.WriteString("}\n")
}

// writeScheme writes the rule of one scheme: its color-scheme and its
// colors — the Material roles, the background, the semantic and chrome
// colors, and the black or white text color for each semantic color.
func writeScheme(b *strings.Builder, s Scheme) {
	t := s.Theme
	fmt.Fprintf(b, ":root[data-oito2-scheme='%s'] {\n", s.Name)
	fmt.Fprintf(b, "\tcolor-scheme: %s;\n", t.Brightness)
	color := func(name, value string) {
		fmt.Fprintf(b, "\t--oito2-%s: %s;\n", name, strings.ToLower(value))
	}
	for _, k := range slices.Sorted(maps.Keys(t.ColorScheme)) {
		color("color-"+kebab(k), t.ColorScheme[k])
	}
	color("color-background", t.Background)
	for _, k := range slices.Sorted(maps.Keys(t.Semantic)) {
		color("color-"+kebab(k), t.Semantic[k])
	}
	for _, k := range []string{"info", "success", "warning"} {
		if v, ok := t.Semantic[k]; ok {
			color("color-on-"+k, foregroundFor(mustHex(v)).hex())
		}
	}
	for _, k := range slices.Sorted(maps.Keys(t.Chrome)) {
		color("chrome-"+kebab(k), t.Chrome[k])
	}
	b.WriteString("}\n")
}

// number formats v with at most two decimals and no trailing zeros.
func number(v float64) string {
	return strconv.FormatFloat(math.Round(v*100)/100, 'f', -1, 64)
}
